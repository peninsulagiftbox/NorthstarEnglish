// Playwright CLI run-code. QuizPanel v2 browser acceptance; requires the isolated test database.
async page => {
 const base=new URL(page.url()).origin, checks=[], errors=[];
 const assert=(ok,message)=>{if(!ok)throw Error(message);};
 const get=async path=>{const r=await page.request.get(base+'/api/v1'+path);assert(r.ok(),'GET '+path+': '+r.status());return r.json();};
 const lesson=tab=>base+'/lesson/demo-01?version=demo-01-v2&tab='+tab;
 const shot=name=>page.screenshot({path:'output/playwright/phase10c2-quiz/'+name+'.png'});
 page.setDefaultTimeout(15000);page.on('pageerror',e=>errors.push(e.message));
 assert((await page.request.get(base+'/api/v1/health')).headers()['x-northstar-test-database']==='true','Isolated database required');
 const idbOpen=()=>new Promise((res,rej)=>{const r=indexedDB.open('northstar-learning-v1',1);r.onsuccess=()=>res(r.result);r.onerror=()=>rej(r.error);});
 const idbRun=(store,mode,op,key,value)=>page.evaluate(`new Promise((res,rej)=>{const rq=indexedDB.open('northstar-learning-v1',1);rq.onsuccess=()=>{const d=rq.result,tx=d.transaction(${JSON.stringify(store)},${JSON.stringify(mode)}),o=tx.objectStore(${JSON.stringify(store)});let out=null;if(${JSON.stringify(op)}==='keys')out=o.getAllKeys();else if(${JSON.stringify(op)}==='put')o.put(${JSON.stringify(value)},${JSON.stringify(key)});else if(${JSON.stringify(op)}==='del')o.delete(${JSON.stringify(key)});tx.oncomplete=()=>res(out&&typeof out.result!=='undefined'?out.result:out);tx.onerror=()=>rej(tx.error);};rq.onerror=()=>rej(rq.error);})`);
 const draftKeys=async()=>idbRun('drafts','readonly','keys');
 const outboxKeys=async()=>idbRun('outbox','readonly','keys');
 const draftPut=(key,value)=>idbRun('drafts','readwrite','put',key,value);
 const outboxPut=(key,value)=>idbRun('outbox','readwrite','put',key,value);
 const draftDel=key=>idbRun('drafts','readwrite','del',key);
 const waitDraft=async(key,count)=>{for(let i=0;i<40;i++){const ok=await page.evaluate(`new Promise(res=>{const rq=indexedDB.open('northstar-learning-v1',1);rq.onsuccess=()=>{const tx=rq.result.transaction('drafts','readonly');const g=tx.objectStore('drafts').get(${JSON.stringify('KEY')});tx.oncomplete=()=>res(!!(g.result&&g.result.answers&&Object.keys(g.result.answers).length===${'COUNT'}));tx.onerror=()=>res(false);};})`.replace('KEY',key).replace('COUNT',String(count)));if(ok)return;await page.waitForTimeout(250);}throw Error('draft not persisted: '+key);};
 const waitText=async(selector,needle)=>{let last=null;for(let i=0;i<40;i++){last=await page.locator(selector).innerText().catch(()=>null);if(last&&last.includes(needle))return;await page.waitForTimeout(250);}const stored=await page.evaluate(`new Promise(res=>{const rq=indexedDB.open('northstar-learning-v1',1);rq.onsuccess=()=>{const tx=rq.result.transaction('drafts','readonly');const all=tx.objectStore('drafts').getAll();tx.oncomplete=()=>res(JSON.stringify(all));tx.onerror=()=>res('read-failed');};})`);throw Error('text not found: '+needle+'; last='+(last||'null')+'; drafts='+stored);};
 let stage='setup';
 try {
  await page.setViewportSize({width:1440,height:900});
  const quiz=await get('/quiz?lessonId=demo-01&versionId=demo-01-v2');
  const setId=quiz.setId,setHash=quiz.setHash;
  assert(quiz.protocolVersion==='quiz-submit-v2'&&quiz.totalCount===3&&quiz.questions.length===3,'v2 protocol with three dynamic questions');
  assert(quiz.questions.every(q=>!('answerKey' in q)&&!('explanation' in q)&&q.options.length>=2&&Number.isInteger(q.ordinal)&&q.sequence>0),'Questions carry no answers before submit');
  const ids=quiz.questions.map(q=>q.id);
  const v2Key=`northstar:quiz:v2:demo-01:demo-01-v2:${setId}:${setHash}`,legacyKey='northstar:quiz:demo-01-v2';
  for(const key of [v2Key,legacyKey]){await draftDel(key);await idbRun('outbox','readwrite','del',key);}
  await page.goto(lesson('quiz'));
  await page.getByRole('radio').first().waitFor();
  assert((await page.locator('.quiz-progress').innerText()).includes('还有 3 题未作答'),'Fresh panel counts three unanswered');
  assert(await page.getByRole('button',{name:'提交本轮 3 题',exact:true}).isDisabled(),'Submit disabled until complete');
  stage='draft-progress';
  await page.getByRole('radio',{name:quiz.questions[0].options[0].text,exact:true}).check();
  assert((await page.locator('.quiz-progress').innerText()).includes('还有 2 题未作答'),'Progress reflects one answered');
  await waitDraft(v2Key,1);
  await page.reload();await page.getByRole('radio').first().waitFor();
 await waitText('.quiz-progress','还有 2 题未作答');
  assert((await page.locator('.quiz-progress').innerText()).includes('还有 2 题未作答'),'Draft survives refresh');
  assert(await page.getByRole('radio',{name:quiz.questions[0].options[0].text,exact:true}).isChecked(),'Restored draft reselects the saved choice');
  const keys=await draftKeys();
  assert(keys.includes(v2Key),'Draft key scopes lesson/version/set/hash: '+v2Key);
  for(const q of quiz.questions.slice(1))await page.getByRole('radio',{name:q.options[0].text,exact:true}).check();
  assert((await page.locator('.quiz-progress').innerText()).includes('全部题目已作答，可以交卷。'),'Complete answers unlock submit');
  assert(!(await page.getByRole('button',{name:'提交本轮 3 题',exact:true}).isDisabled()),'Submit enabled when complete');await shot('complete-draft-1440');
  checks.push('Dynamic count/progress, per-choice draft, refresh recovery, scoped v2 draft key');
  stage='offline-retry';
  const historyBefore=(await get('/quiz?lessonId=demo-01&versionId=demo-01-v2')).history.length;
  await page.route('**/api/v1/quiz/sets/**',route=>route.request().method()==='POST'?route.abort():route.fallback());
  await page.getByRole('button',{name:'提交本轮 3 题',exact:true}).click();
  await page.getByText('原提交待确认，重试不会新增一轮。').waitFor();
  assert((await outboxKeys()).includes(v2Key),'Failed submit retained in outbox');
  await page.unroute('**/api/v1/quiz/sets/**');
  await page.getByRole('button',{name:'重试原提交',exact:true}).click();
  await page.getByRole('heading',{name:/本轮结果：\d \/ 3 题正确/}).waitFor();
  const afterRetry=await get('/quiz?lessonId=demo-01&versionId=demo-01-v2');
  assert(afterRetry.history.length===historyBefore+1,'Retry delivered exactly one run');
  assert(afterRetry.history[0].verified&&afterRetry.history[0].setId===setId&&afterRetry.history[0].setHash===setHash,'Retried run is verified against original set');
  assert(!(await draftKeys()).includes(v2Key),'Delivered draft removed');await shot('offline-retry-1440');
  checks.push('Offline submit keeps single pending command; retry after reconnect creates one verified run');
  stage='legacy-outbox';
  const legacyEvent=crypto.randomUUID();
  const legacyCommand={eventId:legacyEvent,path:'/quiz/attempts',body:{eventId:legacyEvent,lessonId:'demo-01',versionId:'demo-01-v2',answers:Object.fromEntries(ids.map((id,i)=>[id,`demo-01-v2-quiz-0${i+1}-a`])),clientOccurredAt:new Date().toISOString()}};
  await outboxPut(legacyKey,legacyCommand);
  await page.reload();await page.getByRole('radio').first().waitFor();
  await page.getByText('存在旧版待同步提交，将按原路径与内容重试，不升级为题集协议。').waitFor();
  await page.getByRole('button',{name:'重试旧提交',exact:true}).click();
  await page.getByRole('heading',{name:'本轮结果：3 / 3 题正确'}).waitFor();
  const afterLegacy=await get('/quiz?lessonId=demo-01&versionId=demo-01-v2');
  assert(afterLegacy.history.length===historyBefore+2,'Legacy outbox delivered as one additional run on the legacy bridge');
  assert(!(await outboxKeys()).includes(legacyKey),'Legacy command removed after delivery');
  await page.reload();await page.getByRole('radio').first().waitFor();
  assert(!(await page.getByText('存在旧版待同步提交').count()),'Delivered legacy command does not retry again');
  checks.push('Legacy v1 outbox retried on its original path/body exactly once');
  stage='legacy-draft-quarantine';
  await draftPut(legacyKey,Object.fromEntries(ids.map((id,i)=>[id,i===1?'foreign-option':`demo-01-v2-quiz-0${i+1}-a`])));
  await page.reload();await page.getByRole('radio').first().waitFor();
  await page.getByText('旧草稿与当前题集不兼容，已保留；可查看或导出，不会自动覆盖。').waitFor();
  assert((await page.locator('.quiz-progress').innerText()).includes('还有 3 题未作答'),'Incompatible legacy draft is never imported');
  await page.getByText('查看旧草稿',{exact:true}).click();
  assert(await page.getByText('导出旧草稿 JSON').isVisible(),'Quarantined draft stays inspectable/exportable');
  await draftDel(legacyKey);
  checks.push('Incompatible legacy draft quarantined with view/export, no silent merge');
  stage='legacy-draft-import';
  await draftPut(legacyKey,Object.fromEntries(ids.map((id,i)=>[id,`demo-01-v2-quiz-0${i+1}-${i===1?'b':'a'}`])));
  await page.reload();await page.getByRole('radio').first().waitFor();
 await waitText('.quiz-progress','全部题目已作答');
  assert((await page.locator('.quiz-progress').innerText()).includes('全部题目已作答'),'Compatible legacy draft imported into v2 scope');
  assert((await draftKeys()).includes(legacyKey),'Import keeps the original legacy draft');
  await draftDel(v2Key);await draftDel(legacyKey);await shot('legacy-import-1440');
  checks.push('Member-and-option exact legacy draft imports into the v2 scope without deleting history');
  assert(!(await page.locator('body').innerText()).includes('answerKey'),'No answer key in submitted-state DOM');
  assert(errors.length===0,'pageerrors: '+errors.join(';'));
  return {passed:true,checks,pageErrors:errors,browser:await page.evaluate(()=>navigator.userAgent)};
 }catch(e){await shot('failure-'+stage);throw Error(stage+': '+e.message);}
}
